let lang = 'nb';
export const setLang = (l) => { lang = STR[l] ? l : 'nb'; };
export const getLang = () => lang;
export function t(key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.nb[key] ?? key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
export const L = (obj) => (obj ? obj[lang] ?? obj.nb : '');

const SUF = ['', 'K', 'M', 'B', 'T', 'Qa', 'Qi', 'Sx', 'Sp', 'Oc', 'No', 'Dc', 'Ud', 'Dd', 'Td'];
export function fmt(n) {
  if (!Number.isFinite(n)) return '∞';
  if (n < 0) return '-' + fmt(-n);
  let s;
  if (n < 1000) s = n < 10 && n % 1 > 0.05 ? n.toFixed(1) : Math.floor(n + 1e-9).toString();
  else {
    let i = 0;
    while (n >= 999.5 && i < SUF.length - 1) { n /= 1000; i++; }
    if (n >= 1000) return n.toExponential(2);
    s = (n < 10 ? n.toFixed(2) : n < 100 ? n.toFixed(1) : Math.floor(n).toString()) + SUF[i];
  }
  return lang === 'nb' ? s.replace('.', ',') : s;
}
export const money = (n) => '$' + fmt(n);
export function duration(secs) {
  secs = Math.max(0, Math.floor(secs));
  const h = Math.floor(secs / 3600), m = Math.floor((secs % 3600) / 60), s = secs % 60;
  const nb = lang === 'nb';
  if (h) return `${h} ${nb ? 't' : 'h'} ${m} min`;
  if (m) return `${m} min${s ? ` ${s} s` : ''}`;
  return `${s} s`;
}
